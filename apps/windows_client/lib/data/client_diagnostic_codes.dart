/// The diagnostic code for a relay end: the relay's more specific [detail]
/// when it is a known code, else its own reason when that is one, else the
/// grouped user-facing code ([fallback]).
String relayEndCode(Object? reason, String fallback, [Object? detail]) =>
    detail is String && diagnosticCodes.contains(detail)
    ? detail
    : reason is String && diagnosticCodes.contains(reason)
    ? reason
    : fallback;
