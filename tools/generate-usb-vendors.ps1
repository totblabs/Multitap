param(
  [Parameter(Mandatory = $true)][string]$UsbIds,
  [string]$Output = ''
)
if (-not $Output) { $Output = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..\apps\windows_client\windows\runner\usb_vendors_data.h' }
# Builds usb_vendors_data.h (the client's USB vendor-name table) from a copy of
# usb.ids (http://www.linux-usb.org/usb.ids, dual GPL-2.0-or-later / BSD-3-Clause,
# used under BSD-3-Clause; see apps/windows_client/third_party/usb-ids). Only the
# vendor lines are kept ("vvvv<TAB>name\n", sorted), then compressed with the
# Windows Compression API (LZMS) so the client decompresses it with the same API
# (cabinet.dll). Development tool: run by hand when usb.ids is refreshed.
$ErrorActionPreference = 'Stop'
Add-Type -TypeDefinition @'
using System;
using System.Runtime.InteropServices;
public static class Cab {
  [DllImport("cabinet.dll", SetLastError = true)] public static extern bool CreateCompressor(uint algorithm, IntPtr alloc, out IntPtr handle);
  [DllImport("cabinet.dll", SetLastError = true)] public static extern bool Compress(IntPtr h, byte[] src, ulong srcSize, byte[] dst, ulong dstSize, out ulong used);
  [DllImport("cabinet.dll", SetLastError = true)] public static extern bool CloseCompressor(IntPtr h);
}
'@
$utf8 = New-Object System.Text.UTF8Encoding($false)
$lines = [System.IO.File]::ReadAllLines((Resolve-Path $UsbIds), $utf8)
$builder = New-Object System.Text.StringBuilder
foreach ($line in $lines) {
  if ($line -match '^([0-9a-f]{4})  (\S.*)$') {
    $name = $Matches[2].Trim()
    if ($name.Length -gt 0 -and $name -notmatch "[`t`n]") { [void]$builder.Append($Matches[1]).Append("`t").Append($name).Append("`n") }
  }
}
$raw = $utf8.GetBytes($builder.ToString())
$handle = [IntPtr]::Zero
if (-not [Cab]::CreateCompressor(5, [IntPtr]::Zero, [ref]$handle)) { throw 'CreateCompressor failed' }
$buffer = New-Object byte[] ($raw.Length + 4096)
$used = [uint64]0
if (-not [Cab]::Compress($handle, $raw, [uint64]$raw.Length, $buffer, [uint64]$buffer.Length, [ref]$used)) { throw 'Compress failed' }
[void][Cab]::CloseCompressor($handle)
$size = [int]$used
$sha = [System.BitConverter]::ToString([System.Security.Cryptography.SHA256]::Create().ComputeHash($raw)).Replace('-', '').ToLowerInvariant()
$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('// Generated by tools/generate-usb-vendors.ps1 from usb.ids (BSD-3-Clause, see third_party/usb-ids). Do not edit.')
[void]$out.AppendLine('#pragma once')
[void]$out.AppendLine('namespace multitap::usb {')
[void]$out.AppendLine("inline constexpr unsigned kVendorRawSize = $($raw.Length);")
[void]$out.AppendLine("inline constexpr const char* kVendorRawSha256 = `"$sha`";")
[void]$out.AppendLine('inline constexpr unsigned char kVendorBlob[] = {')
for ($i = 0; $i -lt $size; $i += 24) {
  $count = [Math]::Min(24, $size - $i)
  $row = for ($j = 0; $j -lt $count; $j++) { '0x{0:x2}' -f $buffer[$i + $j] }
  [void]$out.AppendLine('  ' + ($row -join ',') + ',')
}
[void]$out.AppendLine('};')
[void]$out.AppendLine('}  // namespace multitap::usb')
[System.IO.File]::WriteAllText($Output, $out.ToString(), $utf8)
"vendors: $(($builder.ToString() -split "`n").Count - 1), raw $($raw.Length) bytes, compressed $size bytes, sha256 $sha"

