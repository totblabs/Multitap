const table = catalogs[lang];
export function t(id, params) {
  const text = table[id];
  if (text === undefined) return id;
  return params ? text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match) : text;
}
// The static markup of index.html (data-i18n, data-i18n-html, data-i18n-attr), as admin/js/i18n.js does.
export function translatePage(root = globalThis.document) {
  const doc = root.ownerDocument ?? root;
  if (lang !== 'ko') {
    for (const node of root.querySelectorAll('[data-i18n-attr]')) for (const pair of node.getAttribute('data-i18n-attr').split(/\s+/)) {
      const at = pair.indexOf(':'); if (at > 0 && table[pair.slice(at + 1)] !== undefined) node.setAttribute(pair.slice(0, at), t(pair.slice(at + 1)));
    }
    for (const node of root.querySelectorAll('[data-i18n-html]')) { const id = node.getAttribute('data-i18n-html'); if (table[id] !== undefined) node.innerHTML = t(id); }
    for (const node of root.querySelectorAll('[data-i18n]')) {
      const id = node.getAttribute('data-i18n'); if (table[id] === undefined) continue;
      const text = [...node.childNodes].find(child => child.nodeType === 3 && child.nodeValue.trim());
      if (!text) { node.textContent = t(id); continue; }
      const [, before, , after] = /^(\s*)([\s\S]*?)(\s*)$/.exec(text.nodeValue);
      text.nodeValue = before + t(id) + after;
    }
  }
  const page = doc.documentElement;
  if (page) { page.setAttribute('lang', lang); page.classList?.remove('i18n-pending'); }
}
